/* --------------------------------------------------------------- helpers */

export function categoriaPorSlug(slug: string): Categoria | undefined {
  return CATEGORIAS.find((c) => c.slug === slug);
}

export function productosDeCategoria(slug: string): Producto[] {
  return PRODUCTOS.filter((p) => p.categoria === slug);
}

export function productosDestacados(): Producto[] {
  return PRODUCTOS.filter((p) => p.destacado && p.disponible);
}

export function precioDesde(p: Producto): number {
  return Math.min(...p.precios.map((x) => x.valor));
}
